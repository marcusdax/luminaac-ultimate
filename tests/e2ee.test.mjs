import * as E from "../e2ee-core.js";
let pass = 0, fail = 0; const t = (n, c) => (c ? pass++ : (fail++, console.log("FAIL", n)));
const k = E.newFamilyKey();
t("key is 32 bytes", E.unb64(k).length === 32);
const s = await E.seal(k, { a: 1, t: "hi" }, "x");
t("sealed prefix", E.isSealed(s) && !s.includes("hi"));
t("roundtrip", (await E.open(k, s, "x"))?.t === "hi");
t("wrong aad fails", (await E.open(k, s, "y")) === null);
t("wrong key fails", (await E.open(E.newFamilyKey(), s, "x")) === null);
t("tamper fails", (await E.open(k, s.slice(0, -3) + (s.at(-3) === "A" ? "B" : "A") + s.slice(-2), "x")) === null);
t("plain text not opened", (await E.open(k, "hello")) === null);
t("random iv", (await E.seal(k, 1)) !== (await E.seal(k, 1)));
const parent = await E.newDeviceKeys(), phone = await E.newDeviceKeys(), evil = await E.newDeviceKeys();
t("pub has no d", !("d" in parent.pub) && "d" in parent.priv);
const c1 = await E.safetyCode(parent.pub, phone.pub), c2 = await E.safetyCode(phone.pub, parent.pub);
t("safety code symmetric 6 digits", c1 === c2 && /^\d{6}$/.test(c1));
t("safety code differs with swapped key", c1 !== (await E.safetyCode(parent.pub, evil.pub)));
const w = await E.wrapFor(k, parent, phone.pub, "req1");
t("wrapped has no key", !w.includes(k));
t("unwrap", (await E.unwrapFrom(w, phone, parent.pub, "req1")) === k);
t("other device can't unwrap", (await E.unwrapFrom(w, evil, parent.pub, "req1")) === null);
t("wrong request id can't unwrap", (await E.unwrapFrom(w, phone, parent.pub, "req2")) === null);
const doc = { version: 2, notes: [{ text: "secret note" }], signals: [{ id: 1 }], profile: { child: "Sam", caregiver: "Mom" } };
const wire = await E.sealDoc(k, doc);
t("wire is v2 ciphertext only", wire.version === 2 && !JSON.stringify(wire).includes("secret") && !JSON.stringify(wire).includes("Sam"));
t("openDoc full", (await E.openDoc(k, wire)).notes[0].text === "secret note");
const child = await E.openDoc(k, { version: 2, e2eeChild: wire.e2eeChild });
t("child part excludes notes", child.signals.length === 1 && !child.notes && child.profile.child === "Sam" && !child.profile.caregiver);
t("plain doc passes through", (await E.openDoc(k, doc)) === doc);
console.log(`${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
