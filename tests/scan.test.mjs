import { rowsOf, Scanner, settings } from "../scan-core.js";
let pass = 0, fail = 0;
const t = (n, c) => (c ? pass++ : (fail++, console.log("FAIL", n)));
const eq = (a, b) => JSON.stringify(a) === JSON.stringify(b);
const rects = [{ top: 0, left: 100 }, { top: 2, left: 0 }, { top: 60, left: 0 }, { top: 61, left: 100 }, { top: 120, left: 0 }];
t("rows grouped and sorted", eq(rowsOf(rects), [[1, 0], [2, 3], [4]]));
const s = settings({ scanMs: 100, scanCfg: { method: "rowcol", loops: 2 } });
t("scanMs clamped", s.scanMs === 600);
t("defaults", settings({}).method === "rowcol" && settings({}).switches === 1);
t("bad method falls back", settings({ scanCfg: { method: "x" } }).method === "rowcol");
let sc = new Scanner(rowsOf(rects), s);
t("starts empty", eq(sc.current(), []));
t("row 1", eq(sc.next(), [1, 0]));
t("row 2", eq(sc.next(), [2, 3]));
t("open row", sc.select().type === "row");
t("item 2", eq(sc.next(), [2]));
t("item 3", eq(sc.next(), [3]));
t("activate 3", eq(sc.select(), { type: "activate", index: 3 }));
t("reset to rows", sc.level === "row" && sc.row === -1);
sc.next(); sc.next(); sc.next();
t("single-item row activates directly", eq(sc.select(), { type: "activate", index: 4 }));
sc = new Scanner(rowsOf(rects), s); sc.next(); sc.select(); sc.next(); sc.next();
t("lap in row returns to rows", eq(sc.next(), [1, 0]) || sc.level === "row");
sc = new Scanner(rowsOf(rects), s);
for (let i = 0; i < 7; i++) sc.next();
t("pauses after loops", sc.paused && eq(sc.next(), []));
t("select resumes", sc.select().type === "resume" && !sc.paused);
const lin = new Scanner(rowsOf(rects), settings({ scanCfg: { method: "linear" } }));
t("linear first", eq(lin.next(), [1]));
lin.next(); lin.next();
t("linear activate", eq(lin.select(), { type: "activate", index: 2 }));
t("empty scanner safe", eq(new Scanner([], s).next(), []) && new Scanner([], s).select().type === "none");
console.log(`${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
